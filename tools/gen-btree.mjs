// Generates cubiomes/tables/btree_ext.h: biome parameter search trees for
// Minecraft versions newer than cubiomes supports (1.21.5+, 26.2, 26.3).
//
// Input: misode/mcmeta "summary" dimension dumps (official multi-noise
// parameter lists), saved as <dir>/<version>-dimension.json. Fetch with e.g.
//   curl -L https://raw.githubusercontent.com/misode/mcmeta/26.3-summary/data/dimension/data.json
//
// The tree is built with a re-implementation of Climate.RTree (tools/rtree.mjs)
// which tools/check-rtree.mjs verifies against cubiomes' own 1.21.4 table.
//
// Usage: node tools/gen-btree.mjs <dir>
import fs from 'fs';
import path from 'path';
import { buildTree, leafFromEntry, flatten } from './rtree.mjs';
import { createEngine } from '../web/wasm-api.js';

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'));
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/gen-btree.mjs <mcmeta-dimension-dir>'); process.exit(1); }

const mod = await WebAssembly.compile(fs.readFileSync(path.join(here, '../web/engine.wasm')));
const eng = await createEngine(mod);
eng.world(28, false, 0n); // MC_1_21_WD for modern biome names
const nameToId = { dappled_forest: 187, sulfur_caves: 188 };
for (let i = 0; i < 256; i++) { const n = eng.biomeName(i); if (n && !(n in nameToId)) nameToId[n] = i; }

const TREES = [
  { name: 'ext2115', version: '1.21.5', note: '1.21.5 - 26.1.2' },
  { name: 'ext262', version: '26.2', note: '26.2' },
  { name: 'ext263', version: '26.3', note: '26.3' },
];

let out = `// Generated by tools/gen-btree.mjs from the official overworld multi-noise
// parameter lists. Do not edit by hand.
#ifndef BTREE_EXT_H_
#define BTREE_EXT_H_
#include <stdint.h>

typedef struct { uint8_t p[6]; uint8_t biome; uint8_t count; uint16_t first; } ExtNode;
typedef struct { const int32_t (*param)[2]; const ExtNode *nodes; int len; } ExtTree;
`;

for (const t of TREES) {
  const list = JSON.parse(fs.readFileSync(path.join(dir, `${t.version}-dimension.json`), 'utf8'))
    .overworld.generator.biome_source.biomes;
  if (list.some((e) => e.parameters.offset)) throw new Error('non-zero offset in ' + t.version);
  const leaves = list.map((e) => {
    const id = nameToId[e.biome.replace('minecraft:', '')];
    if (id === undefined) throw new Error('unknown biome ' + e.biome);
    return leafFromEntry(e, id);
  });
  const { nodes, params } = flatten(buildTree(leaves));
  if (params.length > 255) throw new Error('too many params');
  if (nodes.length > 65535) throw new Error('too many nodes');
  console.log(`${t.version}: ${list.length} entries -> ${nodes.length} nodes, ${params.length} params`);
  out += `\n// ${t.note}: ${list.length} parameter entries\n`;
  out += `static const int32_t ${t.name}_param[][2] = {\n`;
  for (let i = 0; i < params.length; i += 6)
    out += '    ' + params.slice(i, i + 6).map((p) => `{${p[0]},${p[1]}}`).join(',') + ',\n';
  out += `};\nstatic const ExtNode ${t.name}_nodes[] = {\n`;
  for (let i = 0; i < nodes.length; i += 3)
    out += '    ' + nodes.slice(i, i + 3).map((n) => `{{${n.p.join(',')}},${n.leaf ? n.biome : 0},${n.count},${n.first}}`).join(',') + ',\n';
  out += `};\nstatic const ExtTree ${t.name} = { ${t.name}_param, ${t.name}_nodes, ${nodes.length} };\n`;
}

out += `
static uint64_t ext_dist(const ExtTree *t, int idx, const uint64_t np[6])
{
    uint64_t ds = 0;
    const ExtNode *n = &t->nodes[idx];
    for (int i = 0; i < 6; i++)
    {
        int64_t v = (int64_t) np[i];
        int64_t a = v - t->param[n->p[i]][1];
        int64_t b = t->param[n->p[i]][0] - v;
        int64_t d = a > 0 ? a : b > 0 ? b : 0;
        ds += (uint64_t)(d * d);
    }
    return ds;
}

// Mirrors Climate.RTree.SubTree.search, including the warm-start candidate.
static int ext_search(const ExtTree *t, const uint64_t np[6], int idx, int cand)
{
    const ExtNode *n = &t->nodes[idx];
    if (n->count == 0)
        return idx;
    uint64_t bestDist = cand >= 0 ? ext_dist(t, cand, np) : UINT64_MAX;
    int best = cand;
    for (int i = 0; i < n->count; i++)
    {
        int c = n->first + i;
        uint64_t cd = ext_dist(t, c, np);
        if (bestDist > cd)
        {
            int lf = ext_search(t, np, c, best);
            uint64_t ld = (lf == c) ? cd : ext_dist(t, lf, np);
            if (bestDist > ld) { bestDist = ld; best = lf; }
        }
    }
    return best;
}

static int climateToBiomeExt(int mc, const uint64_t np[6], uint64_t *dat)
{
    const ExtTree *t = mc >= MC_26_3 ? &ext263 : mc >= MC_26_2 ? &ext262 : &ext2115;
    int cand = -1;
    if (dat)
    {
        uint64_t a = *dat;
        if (a > 0 && a < (uint64_t) t->len && t->nodes[a].count == 0)
            cand = (int) a;
    }
    int idx = ext_search(t, np, 0, cand);
    if (dat)
        *dat = (uint64_t) idx;
    return t->nodes[idx].biome;
}

#endif
`;
const dest = path.join(here, '../cubiomes/tables/btree_ext.h');
fs.writeFileSync(dest, out);
console.log('wrote', dest, (out.length / 1024).toFixed(0) + ' KB');
